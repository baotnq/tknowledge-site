#!/usr/bin/env python3
"""Build tknowledge.org from src/: every page's text lives once, in
src/pages/<name>.html, and both forms are generated from it — the HTML page a
person reads and the Markdown an AI agent reads (D-206 R1). Also writes
/llms.txt, /llms-full.txt, /sitemap.md, /sitemap.xml and /robots.txt.

    python3 build/build.py            # build from src/ (catalog from src/data/catalog.json)
    python3 build/build.py --fetch    # first refresh the catalog snapshot from /v1/catalog

Standard library only. Edit src/, never the generated files.
"""
import html
import json
import os
import re
import sys
import urllib.request
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://tknowledge.org"
CONNECT_URL = "https://mcp.tknowledge.org/mcp"
CATALOG_API = "https://mcp.tknowledge.org/v1/catalog?status=all"
GENERATED = "<!-- Generated by build/build.py from src/pages/{name}.html — edit the source, not this file. -->"

NAV = [("/personal/", "Personal"), ("/organizations/", "Organisations"), ("/catalog/", "Catalog"),
       ("/blog/", "Blog"), ("/docs/", "Docs")]

# Order of the pages in llms.txt, llms-full.txt and the sitemaps.
ORDER = ["index", "docs", "personal", "organizations", "catalog", "blog",
         "blog-delete-the-chat", "blog-numbers", "privacy"]
SECTIONS = {"index": "Start", "docs": "Start", "personal": "Who it is for", "organizations": "Who it is for",
            "catalog": "Catalog", "blog": "Blog", "blog-delete-the-chat": "Blog", "blog-numbers": "Blog",
            "privacy": "Company"}


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def write(path, text):
    full = os.path.join(ROOT, path.lstrip("/"))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)


# --- source -------------------------------------------------------------------

def load_page(name):
    s = read(f"src/pages/{name}.html")
    m = re.match(r"<!--\n(.*?)\n-->\n", s, re.S)
    meta = dict(line.split(": ", 1) if ": " in line else (line.rstrip(":"), "")
                for line in m.group(1).splitlines())
    body = s[m.end():]
    hero = body.split("<!-- hero -->", 1)[1].split("<!-- main -->", 1)[0].strip()
    main = body.split("<!-- main -->", 1)[1].strip()
    meta["name"] = name
    meta["hero"] = expand(hero)
    meta["main"] = expand(main)
    return meta


def expand(s):
    def inc(m):
        return read(f"src/partials/{m.group(1)}.html").strip()
    s = re.sub(r"<!-- include ([a-z-]+) -->", inc, s)
    if "<!-- catalog -->" in s:
        s = s.replace("<!-- catalog -->", catalog_html())
    return s


# --- catalog, rendered at build time (no content that only JavaScript draws) ----

AXES = ["who", "what", "when", "where"]


def catalog_data():
    return json.loads(read("src/data/catalog.json"))


def fetch_catalog():
    with urllib.request.urlopen(CATALOG_API, timeout=30) as r:
        data = json.load(r)
    write("src/data/catalog.json", json.dumps(data, ensure_ascii=False, indent=1) + "\n")


def esc(s):
    return html.escape(str(s), quote=True)


def code_spans(s):
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", esc(s))


def paste_text(e):
    return ("Read entry " + e["id"] + " of the T-knowledge catalog (https://mcp.tknowledge.org/v1/catalog). "
            "Show it to me in my language. If I approve, add it to my T-knowledge store with instruction_add, catalog "
            + e["id"] + ": the English unchanged, and your translation beside it.")


def entry_html(e):
    t = e.get("tags") or {}
    status = e["status"]
    if status == "superseded":
        status_text = "superseded by " + esc(e.get("superseded_by", ""))
    elif status == "withdrawn":
        status_text = "withdrawn" + (" — " + esc(e["reason"]) if e.get("reason") else "")
    else:
        status_text = "current"
    data = " ".join(f'data-{a}="{esc(" ".join(t.get(a) or []))}"' for a in AXES)
    name = e.get("title") or ("Definition: " + e["term"] if e.get("term") else "")
    rows = ""
    if e.get("evidence"):
        rows += "<dt>Incident</dt><dd>" + (esc(e["incident_on"]) + " — " if e.get("incident_on") else "") + esc(e["evidence"]) + "</dd>"
    if e.get("source"):
        rows += "<dt>Source</dt><dd>" + esc(e["source"]) + "</dd>"
    why = e.get("definition_why") or t.get("why")
    if why:
        rows += "<dt>Why</dt><dd>" + esc(why) + "</dd>"
    if t.get("how"):
        rows += "<dt>How</dt><dd>" + esc(t["how"]) + "</dd>"
    chips = "".join(f'<span class="tag">{a}: {esc(v)}</span>' for a in AXES for v in (t.get(a) or []))
    added = " · added " + esc(e["approved_at"][:10]) if e.get("approved_at") else ""
    take = ""
    if e["status"] == "current":
        take = ('<details><summary>Add to your store</summary><div class="say"><span>' + esc(paste_text(e)) +
                '</span><button class="copy" type="button">Copy</button></div></details>')
    return (f'<li class="entry{"" if e["status"] == "current" else " old"}" id="{esc(e["id"])}" {data}>'
            f'<header><span class="bp">{esc(e["id"])}</span><span class="meta">{esc(e["kind"])} · {status_text}{added}</span></header>'
            + (f"<p><b>{esc(name)}</b></p>" if name else "")
            + f'<p class="text">{code_spans(e["text"])}</p>'
            + (f"<dl>{rows}</dl>" if rows else "")
            + (f"<p>{chips}</p>" if chips else "")
            + take + "</li>")


def catalog_html():
    entries = catalog_data()["entries"]
    cur = [e for e in entries if e["status"] == "current"]
    old = [e for e in entries if e["status"] != "current"]
    out = (f'<p class="small" id="count" aria-live="polite">{len(cur)} current entries in the catalog.</p>\n'
           '<ol class="entries" id="entries">' + "".join(entry_html(e) for e in cur) + "</ol>\n")
    if old:
        out += ('<section id="old-entries"><h2>Superseded and withdrawn</h2>'
                '<ol class="entries">' + "".join(entry_html(e) for e in old) + "</ol></section>\n")
    return out


# --- HTML ---------------------------------------------------------------------

def page_html(p):
    md = p["md"]
    nav = "".join(f'<a href="{href}"' + (' aria-current="page"' if href == p["path"] else "") + f">{label}</a>"
                  for href, label in NAV)
    jsonld = ""
    if p["name"] == "index":
        jsonld = ('<script type="application/ld+json">' + json.dumps({
            "@context": "https://schema.org", "@type": "SoftwareApplication", "name": "T-knowledge",
            "url": SITE + "/", "description": text_of(read("src/partials/definition.html")),
            "applicationCategory": "BusinessApplication", "operatingSystem": "Any (MCP server)",
            "installUrl": CONNECT_URL}, ensure_ascii=False) + "</script>\n")
    scripts = "".join(f'<script src="{s.strip()}"></script>\n' for s in p.get("scripts", "").split(",") if s.strip())
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
{GENERATED.format(name=p["name"])}
<title>{esc(p["title"])}</title>
<meta name="description" content="{esc(p["description"])}">
<link rel="canonical" href="{SITE}{p["path"]}">
<link rel="alternate" type="text/markdown" href="{md}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,opsz,wght@0,8..60,400..700;1,8..60,400&display=swap">
<link rel="stylesheet" href="/site.css">
{jsonld}</head>
<body>
<header class="{p["header"]}">
  <div class="in">
    <nav aria-label="Main">
      <a class="brand" href="/">T-knowledge</a>
      <span class="links">{nav}</span>
    </nav>
    {p["hero"]}
  </div>
</header>

{p["main"]}

{read("src/partials/footer.html").strip()}
{scripts}</body>
</html>
"""


# --- Markdown -----------------------------------------------------------------

VOID = {"br", "img", "hr", "input", "meta", "link", "source", "wbr"}
BLOCK = {"p", "div", "section", "main", "header", "footer", "ul", "ol", "li", "table", "thead", "tbody",
         "tr", "td", "th", "dl", "dt", "dd", "details", "summary", "blockquote", "pre", "h1", "h2",
         "h3", "h4", "h5", "h6", "nav", "article"}


class Node:
    def __init__(self, tag, attrs, parent):
        self.tag, self.attrs, self.parent, self.children = tag, dict(attrs), parent, []


class Tree(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("root", [], None)
        self.cur = self.root

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs, self.cur)
        self.cur.children.append(n)
        if tag not in VOID:
            self.cur = n

    def handle_startendtag(self, tag, attrs):
        self.cur.children.append(Node(tag, attrs, self.cur))

    def handle_endtag(self, tag):
        n = self.cur
        while n is not self.root and n.tag != tag:
            n = n.parent
        if n is not self.root:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.children.append(data)


def parse(s):
    t = Tree()
    t.feed(s)
    return t.root


def skipped(n):
    a = n.attrs
    return (n.tag in ("script", "style", "button", "nav", "select", "input", "template")
            or a.get("role") == "tablist" or "data-md-skip" in a or a.get("aria-hidden") == "true")


def absolute(href):
    if href.startswith("/"):
        return SITE + href
    return href


def inline(n):
    """Inline Markdown of a node's children, whitespace collapsed."""
    out = []
    prev_element = False
    for c in n.children:
        if isinstance(c, str):
            out.append(re.sub(r"\s+", " ", c))
            prev_element = False
            continue
        if skipped(c):
            continue
        t = c.tag
        if t == "br":
            out.append(" ")
            prev_element = False
            continue
        inner = inline(c).strip()
        if not inner:
            continue
        # Two elements side by side with nothing between them are separate
        # items on the page (a link row, a ledger row): keep them apart.
        so_far = "".join(out)
        if so_far.strip() and not so_far.endswith(" ") and (
                (prev_element and t in ("a", "span", "strong", "b")) or t == "small"):
            out.append(" · ")
        prev_element = t in ("a", "span", "strong", "b")
        if t == "a":
            href = c.attrs.get("href", "")
            out.append(f"[{inner}]({absolute(href)})" if href and not href.startswith("#") else inner)
        elif t == "code":
            out.append("`" + inner + "`")
        elif t in ("strong", "b"):
            out.append("**" + inner + "**")
        elif t in ("em", "i"):
            out.append("*" + inner + "*")
        elif t in BLOCK:
            out.append(" " + inner + " ")
        else:
            out.append(inner)
    return re.sub(r" {2,}", " ", "".join(out))


def blocks(n, depth=0):
    """Markdown blocks of a node's children, as a list of strings."""
    out, buf = [], []

    def flush():
        text = "".join(buf).strip()
        if text:
            out.append(re.sub(r"\s+", " ", text))
        buf.clear()

    run = []

    def flush_run():
        if run:
            w = Node("x", [], None)
            w.children = list(run)
            buf.append(inline(w))
            run.clear()

    for c in n.children:
        if isinstance(c, str) or (not skipped(c) and c.tag not in BLOCK):
            run.append(c)
            continue
        if skipped(c):
            continue
        t = c.tag
        flush_run()
        flush()
        if "data-md-list" in c.attrs:
            items = [inline_wrap(x).strip() for x in c.children if not isinstance(x, str) and not skipped(x)]
            out.append("\n".join("- " + i for i in items if i))
            continue
        if c.attrs.get("role") == "tabpanel" and c.attrs.get("aria-labelledby") in LABELS:
            out.append("**" + LABELS[c.attrs["aria-labelledby"]] + "**")
        if t in ("h1", "h2", "h3", "h4", "h5", "h6"):
            out.append("#" * int(t[1]) + " " + inline(c).strip())
        elif t == "p":
            text = inline(c).strip()
            if text:
                out.append(text)
        elif t == "pre":
            out.append("```\n" + "".join(text_nodes(c)).strip("\n") + "\n```")
        elif t in ("ul", "ol"):
            out.append(list_md(c, t == "ol", depth))
        elif t == "table":
            out.append(table_md(c))
        elif t == "dl":
            out.append(dl_md(c))
        elif t == "blockquote":
            out.append("\n".join("> " + line for line in "\n\n".join(blocks(c)).splitlines()))
        elif t == "summary":
            level = c.attrs.get("data-md-heading")
            text = inline(c).strip()
            out.append(("#" * int(level) + " " + text) if level else "**" + text + "**")
        else:
            out.extend(blocks(c, depth))
    flush_run()
    flush()
    return out


def inline_wrap(c):
    w = Node("x", [], None)
    w.children = [c]
    return inline(w)


def text_nodes_all(n):
    for c in n.children:
        yield c if isinstance(c, str) else "".join(text_nodes_all(c))


def text_nodes(n):
    for c in n.children:
        if isinstance(c, str):
            yield c
        elif not skipped(c):
            yield from text_nodes(c)


def list_md(n, ordered, depth):
    lines, i = [], 0
    for li in n.children:
        if isinstance(li, str) or li.tag != "li":
            continue
        i += 1
        mark = f"{i}. " if ordered else "- "
        parts = blocks(li, depth + 1)
        if not parts:
            continue
        pad = "   " if ordered else "  "
        first, rest = parts[0], parts[1:]
        lines.append(mark + first.replace("\n", "\n" + pad))
        for r in rest:
            lines.append(pad + r.replace("\n", "\n" + pad))
    return "\n".join(lines)


def cells(tr):
    return [inline(c).strip().replace("|", "\\|") for c in tr.children
            if not isinstance(c, str) and c.tag in ("td", "th")]


def rows_of(n):
    for c in n.children:
        if isinstance(c, str):
            continue
        if c.tag == "tr":
            yield c
        elif c.tag in ("thead", "tbody", "tfoot"):
            yield from rows_of(c)


def table_md(n):
    rows = [cells(tr) for tr in rows_of(n)]
    if not rows:
        return ""
    w = max(len(r) for r in rows)
    rows = [r + [""] * (w - len(r)) for r in rows]
    head, body = rows[0], rows[1:]
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * w] + ["| " + " | ".join(r) + " |" for r in body])


def dl_md(n):
    lines, term = [], None
    for c in n.children:
        if isinstance(c, str):
            continue
        if c.tag == "div":
            lines.append(dl_md(c))
            continue
        if c.tag == "dt":
            term = inline(c).strip()
        elif c.tag == "dd":
            lines.append(f"- **{term}** {inline(c).strip()}" if term else "- " + inline(c).strip())
            term = None
    return "\n".join(l for l in lines if l)


LABELS = {}


def md_of(fragment):
    root = parse(fragment)
    for n in walk(root):
        if n.tag == "button" and n.attrs.get("role") == "tab" and n.attrs.get("id"):
            LABELS[n.attrs["id"]] = re.sub(r"\s+", " ", "".join(text_nodes_all(n))).strip()
    first = [n for n in walk(root) if "data-md-first" in n.attrs]
    for n in first:
        n.parent.children.remove(n)
    parts = []
    for n in first:
        parts += blocks(wrap(n))
    parts += blocks(root)
    return "\n\n".join(p for p in parts if p.strip())


def wrap(n):
    w = Node("root", [], None)
    w.children = [n]
    return w


def walk(n):
    for c in n.children:
        if not isinstance(c, str):
            yield c
            yield from walk(c)


def text_of(fragment):
    return re.sub(r"\s+", " ", "".join(text_nodes(parse(fragment)))).strip()


def page_md(p):
    body = md_of(p["hero"] + "\n" + p["main"])
    foot = md_of(read("src/partials/footer.html"))
    return (f"<!-- {p['title']} · {SITE}{p['path']} · Markdown form of the same page, generated from one source -->\n\n"
            f"{body}\n\n---\n\n{foot}\n")


# --- indexes ------------------------------------------------------------------

def llms_txt(pages):
    d = text_of(read("src/partials/definition.html"))
    out = ["# T-knowledge", "", "> " + d, "",
           f"Connect an AI agent: MCP server `{CONNECT_URL}` (OAuth; sign in by email). "
           f"Every page below is also served as Markdown at the same URL with `Accept: text/markdown`.", ""]
    seen = []
    for name in ORDER:
        sec = SECTIONS[name]
        if sec not in seen:
            seen.append(sec)
            out += ["", f"## {sec}", ""]
        p = pages[name]
        out.append(f"- [{p['title']}]({SITE}{p['md']}): {p['description']}")
    out += ["", "## Optional", "",
            f"- [All pages in one file]({SITE}/llms-full.txt): every page above, concatenated.",
            f"- [Catalog as JSON](https://mcp.tknowledge.org/v1/catalog): the instruction catalog, machine-readable.",
            f"- [Standard](https://baotrinh.com/standard/): the standard T-knowledge implements."]
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"


def sitemap_md(pages):
    out = ["# Sitemap — tknowledge.org", ""]
    for name in ORDER:
        p = pages[name]
        out.append(f"- [{p['title']}]({SITE}{p['path']}) — Markdown: {SITE}{p['md']}")
    return "\n".join(out) + "\n"


def sitemap_xml(pages):
    urls = "".join(f"  <url><loc>{SITE}{pages[n]['path']}</loc></url>\n" for n in ORDER)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + urls + "</urlset>\n")


def robots_txt():
    bots = json.loads(read("edge/agents.json"))["robots_allow"]
    out = ["# AI agents and search engines are welcome; the whole site is public.", ""]
    for b in bots:
        out += [f"User-agent: {b}", "Allow: /", ""]
    out += ["User-agent: *", "Allow: /", "", f"Sitemap: {SITE}/sitemap.xml"]
    return "\n".join(out) + "\n"


def main():
    if "--fetch" in sys.argv:
        fetch_catalog()
    pages = {n: load_page(n) for n in ORDER}
    for n, p in pages.items():
        out = "index.html" if p["path"] == "/" else p["path"].strip("/") + "/index.html"
        write(out, page_html(p))
        write(p["md"], page_md(p))
    write("llms.txt", llms_txt(pages))
    write("llms-full.txt", "\n\n".join(page_md(pages[n]) for n in ORDER))
    write("sitemap.md", sitemap_md(pages))
    write("sitemap.xml", sitemap_xml(pages))
    write("robots.txt", robots_txt())
    write("edge/routes.json", json.dumps({pages[n]["path"]: pages[n]["md"] for n in ORDER}, indent=1) + "\n")
    print("built", len(pages), "pages")


if __name__ == "__main__":
    main()
